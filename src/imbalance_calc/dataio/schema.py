"""Опис структури місячного файлу ГП.

Аркуші мають однаковий формат: рядок 1 — заголовок (``Доба``, ``Зона``,
``1 год`` … ``24 год``), далі по одному рядку на добу. Відповідність аркушів
величинам методики — docs/METHODOLOGY.md, розділ 8.

Кількість аркушів **не стала**: 13, 14, 15 або 16. Це не дефект вивантаження,
а відображення того, що відбувалось у місяці — аркуші з командами ОСП
зʼявляються лише тоді, коли такі команди були. Тому обовʼязкові аркуші
відокремлені від необовʼязкових: див. docs/gp_file_format_variations.md.
"""

