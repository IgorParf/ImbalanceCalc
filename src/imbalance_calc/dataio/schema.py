#: Аркуш -> назва колонки, у тому порядку, в якому аркуші йдуть у файлі ГП.
#:
#: Увага: аркуші БЕЗ позначки «без дельт» містять величини З урахуванням
#: ΔW/ΔS (індекс Δ у методиці), а «без дельт» — базові величини.
