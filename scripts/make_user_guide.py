def save(path: Path) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    build().save(path)
    return path


if __name__ == "__main__":
    target = (
        Path(sys.argv[1])
        if len(sys.argv) > 1
        else Path(__file__).resolve().parents[1] / "docs" / "user-guide.docx"
    )
    print(f"Інструкцію збережено: {save(target)}")
