ACCENT = RGBColor(0x1F, 0x4E, 0x79)
NOTE_FILL = "EEF2F7"
WARN_FILL = "FDE9E7"


def _shade(paragraph, color: str) -> None:
    """Залити абзац кольором — для приміток і попереджень."""
    shading = OxmlElement("w:shd")
    shading.set(qn("w:val"), "clear")
    shading.set(qn("w:fill"), color)
    paragraph._p.get_or_add_pPr().append(shading)


def _note(document: Document, text: str, warning: bool = False) -> None:
    paragraph = document.add_paragraph()
    run = paragraph.add_run(("Увага. " if warning else "Порада. ") + text)
    run.font.size = Pt(10)
    paragraph.paragraph_format.space_before = Pt(6)
    paragraph.paragraph_format.space_after = Pt(6)
    paragraph.paragraph_format.left_indent = Cm(0.4)
    _shade(paragraph, WARN_FILL if warning else NOTE_FILL)


def _steps(document: Document, items: list[str]) -> None:
    for item in items:
        document.add_paragraph(item, style="List Number")


def _bullets(document: Document, items: list[str]) -> None:
    for item in items:
        document.add_paragraph(item, style="List Bullet")


def _table(document: Document, header: list[str], rows: list[list[str]]) -> None:
    table = document.add_table(rows=1, cols=len(header))
    table.style = "Light Grid Accent 1"
    table.alignment = WD_TABLE_ALIGNMENT.LEFT
    for cell, title in zip(table.rows[0].cells, header, strict=True):
        cell.text = title
        for paragraph in cell.paragraphs:
            for run in paragraph.runs:
                run.bold = True
    for row in rows:
        cells = table.add_row().cells
        for cell, value in zip(cells, row, strict=True):
            cell.text = value
    document.add_paragraph()


def _setup_styles(document: Document) -> None:
    normal = document.styles["Normal"]
    normal.font.name = "Calibri"
    normal.font.size = Pt(11)
    normal._element.rPr.rFonts.set(qn("w:eastAsia"), "Calibri")
    normal.paragraph_format.space_after = Pt(6)

    for name, size in (("Heading 1", 16), ("Heading 2", 13)):
        style = document.styles[name]
        style.font.name = "Calibri"
        style.font.size = Pt(size)
        style.font.color.rgb = ACCENT
        style.font.bold = True


